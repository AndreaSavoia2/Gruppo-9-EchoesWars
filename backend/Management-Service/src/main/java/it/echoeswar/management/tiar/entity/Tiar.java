package it.echoeswar.management.tiar.entity;

import jakarta.persistence.*;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

import java.time.LocalDateTime;

/**
 * JPA entity representing a tiar, mapped to the {@code tiars} table.
 *
 * <p>A tiar has a business code, localized names (Italian and English) and a
 * {@link Level}. It is referenced by {@code Card}, where each card is linked to
 * exactly one tiar. Creation and update timestamps are managed automatically
 * by Hibernate.</p>
 */
@Entity
@Table(name="tiars")
public class Tiar {

    /**
     * Primary key, auto-generated by the database (identity column).
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private byte id;

    /**
     * Business code that identifies the tiar (max 100 characters).
     */
    @Column(nullable = false, length = 100)
    private String code;

    /**
     * Tiar name in Italian (max 100 characters).
     */
    @Column(nullable = false, length = 100)
    private String nameIt;

    /**
     * Tiar name in English (max 100 characters).
     */
    @Column(nullable = false, length = 100)
    private String nameEn;

    /**
     * Level of the tiar, persisted as its enum name (string) rather than its ordinal.
     */
    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 100)
    private Level level;

    /**
     * Whether the tiar is enabled and available in the game.
     */
    @Column(nullable = false)
    private boolean enabled;

    /**
     * Timestamp of when the tiar was created; set automatically and never updated.
     */
    @CreationTimestamp
    @Column(nullable = false, updatable = false)
    private LocalDateTime created;

    /**
     * Timestamp of the last update; refreshed automatically on every change.
     */
    @UpdateTimestamp
    @Column(nullable = false)
    private LocalDateTime updated;
}
