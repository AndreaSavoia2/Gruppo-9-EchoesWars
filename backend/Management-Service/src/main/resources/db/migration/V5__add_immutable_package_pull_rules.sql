-- Ogni versione commerciale possiede un insieme di regole immutabile.
-- Per cambiare comportamento si crea una nuova package_version e una nuova regola.
CREATE TABLE package_pull_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_version_id BIGINT NOT NULL,
    cards_per_package INTEGER NOT NULL,
    guaranteed_common_cards INTEGER NOT NULL,
    guaranteed_rare_cards INTEGER NOT NULL,
    cycle_length INTEGER NOT NULL,
    random_common_threshold INTEGER NOT NULL,
    random_rare_threshold INTEGER NOT NULL,

    CONSTRAINT uq_package_pull_rule_version UNIQUE (package_version_id),
    CONSTRAINT fk_package_pull_rule_version
        FOREIGN KEY (package_version_id) REFERENCES package_versions (id)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT chk_package_pull_rule_card_distribution CHECK (
        cards_per_package > 0
        AND guaranteed_common_cards >= 0
        AND guaranteed_rare_cards >= 0
        AND guaranteed_common_cards + guaranteed_rare_cards < cards_per_package
    ),
    CONSTRAINT chk_package_pull_rule_cycle CHECK (cycle_length > 0),
    CONSTRAINT chk_package_pull_rule_thresholds CHECK (
        random_common_threshold >= 0
        AND random_common_threshold <= random_rare_threshold
        AND random_rare_threshold <= 100
    )
);

-- Le versioni già esistenti mantengono esattamente le regole storiche 5/3/1/10/85/13/2.
