-- Anche gli aggiornamenti eseguiti direttamente sul database non possono riscrivere la storia.
CREATE FUNCTION reject_package_pull_rule_mutation()
RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION
        'Package pull rules are immutable. Create a new package version and a new rule instead.';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_package_pull_rules_immutable
BEFORE UPDATE OR DELETE ON package_pull_rules
FOR EACH ROW
EXECUTE FUNCTION reject_package_pull_rule_mutation();

