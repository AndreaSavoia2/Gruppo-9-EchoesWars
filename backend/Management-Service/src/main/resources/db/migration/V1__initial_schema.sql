    CONSTRAINT chk_game_rule_initial_life CHECK (initial_life > 0),
    CONSTRAINT chk_game_rule_max_rounds CHECK (max_rounds > 0)
);

CREATE TABLE challenges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    challenger_user_id UUID NOT NULL,
    challenged_user_id UUID NOT NULL,
    challenger_deck_id BIGINT NOT NULL,
    challenged_deck_id BIGINT,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP(6),
    accepted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    rejected_at TIMESTAMP(6) WITHOUT TIME ZONE,
    cancelled_at TIMESTAMP(6) WITHOUT TIME ZONE,
    expires_at TIMESTAMP(6) WITHOUT TIME ZONE,

    CONSTRAINT fk_challenges_challenger_user
        FOREIGN KEY (challenger_user_id) REFERENCES users (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_challenges_challenged_user
        FOREIGN KEY (challenged_user_id) REFERENCES users (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_challenges_challenger_deck
        FOREIGN KEY (challenger_deck_id) REFERENCES decks (id)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_challenges_challenged_deck
        FOREIGN KEY (challenged_deck_id) REFERENCES decks (id)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT chk_challenges_different_users CHECK (challenger_user_id <> challenged_user_id),
    CONSTRAINT chk_challenges_status
        CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'CANCELLED', 'EXPIRED'))
);

CREATE TABLE matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    challenge_id BIGINT NOT NULL,
    rules_version_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    result VARCHAR(30),
    winner_user_id UUID,
    player_one_final_life INTEGER,
    player_two_final_life INTEGER,
    total_rounds INTEGER,
    input_snapshot JSONB NOT NULL,
    replay JSONB,
    engine_version VARCHAR(100),
    random_seed VARCHAR(255),
    failure_reason TEXT,
    started_at TIMESTAMP(6) WITHOUT TIME ZONE,
    ended_at TIMESTAMP(6) WITHOUT TIME ZONE,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP(6),

    CONSTRAINT uq_matches_challenge UNIQUE (challenge_id),
    CONSTRAINT fk_matches_challenge
        FOREIGN KEY (challenge_id) REFERENCES challenges (id)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_matches_rules_version
        FOREIGN KEY (rules_version_id) REFERENCES game_rule_versions (id)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_matches_winner
        FOREIGN KEY (winner_user_id) REFERENCES users (id)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT chk_matches_status
        CHECK (status IN ('PENDING', 'RUNNING', 'COMPLETED', 'FAILED', 'ABORTED')),
    CONSTRAINT chk_matches_result
        CHECK (result IS NULL OR result IN ('PLAYER_ONE_WIN', 'PLAYER_TWO_WIN', 'DRAW')),
    CONSTRAINT chk_matches_life
        CHECK (
            (player_one_final_life IS NULL OR player_one_final_life >= 0)
            AND (player_two_final_life IS NULL OR player_two_final_life >= 0)
        ),
    CONSTRAINT chk_matches_rounds CHECK (total_rounds IS NULL OR total_rounds >= 0)
);

CREATE TABLE simulation_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    attempt_count INTEGER NOT NULL DEFAULT 0,
    available_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP(6),
    locked_at TIMESTAMP(6) WITHOUT TIME ZONE,
    started_at TIMESTAMP(6) WITHOUT TIME ZONE,
    completed_at TIMESTAMP(6) WITHOUT TIME ZONE,
    last_error TEXT,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP(6),
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP(6),

    CONSTRAINT uq_simulation_jobs_match UNIQUE (match_id),
    CONSTRAINT fk_simulation_jobs_match
        FOREIGN KEY (match_id) REFERENCES matches (id)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT chk_simulation_jobs_status
        CHECK (status IN ('PENDING', 'RUNNING', 'COMPLETED', 'FAILED')),
    CONSTRAINT chk_simulation_jobs_attempts CHECK (attempt_count >= 0)
);
