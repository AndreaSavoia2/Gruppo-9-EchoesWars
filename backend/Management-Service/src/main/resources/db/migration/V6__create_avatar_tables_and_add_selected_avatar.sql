CREATE TABLE avatars (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(100) NOT NULL,
    name_it VARCHAR(150) NOT NULL,
    name_en VARCHAR(150) NOT NULL,
    image_url VARCHAR(500) NOT NULL,
    is_exclusive BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP(6),

    CONSTRAINT uq_avatars_code UNIQUE (code)
);

ALTER TABLE users
    DROP COLUMN IF EXISTS avatar_url,
    ADD COLUMN selected_avatar_id BIGINT;

CREATE TABLE user_avatars (
    user_id UUID NOT NULL,
    avatar_id BIGINT NOT NULL,
    unlocked_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP(6),

    PRIMARY KEY (user_id, avatar_id),
    CONSTRAINT fk_user_avatars_user
        FOREIGN KEY (user_id) REFERENCES users(id)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_user_avatars_avatar
        FOREIGN KEY (avatar_id) REFERENCES avatars(id)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

ALTER TABLE users
    ADD CONSTRAINT fk_users_selected_avatar
        FOREIGN KEY (id, selected_avatar_id) REFERENCES user_avatars(user_id, avatar_id)
        ON DELETE RESTRICT ON UPDATE CASCADE;
