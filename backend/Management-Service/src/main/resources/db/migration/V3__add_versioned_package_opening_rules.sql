-- Le regole sono configurate per versione; gli acquisti ne conservano una copia storica.
CREATE TABLE package_opening_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_version_id BIGINT NOT NULL,
    cards_per_package INTEGER NOT NULL,
    guaranteed_common_cards INTEGER NOT NULL,
    guaranteed_rare_cards INTEGER NOT NULL,
    guaranteed_legendary_cards_on_cycle INTEGER NOT NULL,
    cycle_length INTEGER NOT NULL,
    random_common_percentage INTEGER NOT NULL,
    random_rare_percentage INTEGER NOT NULL,
    random_legendary_percentage INTEGER NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP(6),

    CONSTRAINT uq_package_opening_rule_version UNIQUE (package_version_id),
    CONSTRAINT fk_package_opening_rule_version
        FOREIGN KEY (package_version_id) REFERENCES package_versions (id)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT chk_package_opening_rule_cards CHECK (
        cards_per_package > 0
        AND guaranteed_common_cards >= 0
        AND guaranteed_rare_cards >= 0
        AND guaranteed_legendary_cards_on_cycle >= 0
        AND guaranteed_common_cards + guaranteed_rare_cards <= cards_per_package
        AND guaranteed_common_cards + guaranteed_rare_cards
            + guaranteed_legendary_cards_on_cycle <= cards_per_package
    ),
    CONSTRAINT chk_package_opening_rule_cycle CHECK (cycle_length > 0),
    CONSTRAINT chk_package_opening_rule_percentages CHECK (
        random_common_percentage >= 0
        AND random_rare_percentage >= 0
        AND random_legendary_percentage >= 0
        AND random_common_percentage + random_rare_percentage + random_legendary_percentage = 100
    )
);

