
CREATE TABLE player_ratings (
                                user_id UUID PRIMARY KEY,
                                mmr INTEGER NOT NULL DEFAULT 1000,
                                created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP(6),
                                updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP(6),

                                CONSTRAINT fk_player_ratings_user
                                    FOREIGN KEY (user_id) REFERENCES users (id)
                                        ON DELETE RESTRICT ON UPDATE CASCADE,
                                CONSTRAINT chk_player_ratings_mmr
                                    CHECK (mmr >= 0)
);

CREATE TABLE matchmaking_requests (
                                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      user_id UUID NOT NULL,
                                      deck_id BIGINT NOT NULL,
                                      mmr_at_enqueue INTEGER NOT NULL,
                                      status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
                                      match_id BIGINT,
                                      created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP(6),
                                      updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP(6),
                                      expires_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,

                                      CONSTRAINT fk_matchmaking_requests_user
                                          FOREIGN KEY (user_id) REFERENCES users (id)
                                              ON DELETE RESTRICT ON UPDATE CASCADE,
                                      CONSTRAINT fk_matchmaking_requests_deck
                                          FOREIGN KEY (deck_id) REFERENCES decks (id)
                                              ON DELETE RESTRICT ON UPDATE CASCADE,
                                      CONSTRAINT fk_matchmaking_requests_match
                                          FOREIGN KEY (match_id) REFERENCES matches (id)
                                              ON DELETE RESTRICT ON UPDATE CASCADE,
                                      CONSTRAINT chk_matchmaking_requests_mmr
                                          CHECK (mmr_at_enqueue >= 0),
                                      CONSTRAINT chk_matchmaking_requests_status
                                          CHECK (status IN ('PENDING', 'COMBINED', 'CANCELLED', 'EXPIRED')),
                                      CONSTRAINT chk_matchmaking_requests_expiration
                                          CHECK (expires_at > created_at),
                                      CONSTRAINT chk_matchmaking_requests_match_association
                                          CHECK (
                                              (status = 'COMBINED' AND match_id IS NOT NULL)
                                                  OR (
                                                  status IN ('PENDING', 'CANCELLED', 'EXPIRED')
                                                      AND match_id IS NULL
                                                  )
                                              )
);

-- Impedisce due ricerche contemporaneamente in attesa per lo stesso giocatore.
CREATE UNIQUE INDEX ux_matchmaking_requests_waiting_user
    ON matchmaking_requests (user_id)
    WHERE status = 'PENDING';

-- Supporta la selezione della ricerca più vecchia da parte dello scheduler.
CREATE INDEX ix_matchmaking_requests_waiting_created
    ON matchmaking_requests (created_at, id)
    WHERE status = 'PENDING';

-- Supporta la scadenza periodica delle ricerche ancora attive.
CREATE INDEX ix_matchmaking_requests_waiting_expiration
    ON matchmaking_requests (expires_at)
    WHERE status = 'PENDING';

-- Supporta la lettura delle richieste associate a una partita.
CREATE INDEX ix_matchmaking_requests_match_id
    ON matchmaking_requests (match_id);

-- Lo snapshot può essere valorizzato una sola volta dopo la generazione dell'ID della challenge.
CREATE FUNCTION prevent_challenge_input_snapshot_change()
    RETURNS TRIGGER
    LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.input_snapshot IS NOT NULL
            AND NEW.input_snapshot IS DISTINCT FROM OLD.input_snapshot THEN
        RAISE EXCEPTION USING
            ERRCODE = '23514',
            MESSAGE = 'Lo snapshot di input della challenge è immutabile.';
END IF;

RETURN NEW;
END;
$$;

CREATE TRIGGER trg_challenges_input_snapshot_immutable
    BEFORE UPDATE OF input_snapshot ON challenges
    FOR EACH ROW
    EXECUTE FUNCTION prevent_challenge_input_snapshot_change();